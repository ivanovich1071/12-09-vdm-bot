"""О чём реплика — без обращения к модели.

Нужно в двух местах, и оба важны.

**Маршрутизатору** — чтобы не звать модель там, где всё очевидно. «Привет»,
«2.1.14», «покажи станки для мастерских» разбираются регулярками за микросекунды,
а вызов маршрутизатора стоит денег и полсекунды задержки.

**Ядру, когда модели нет.** Раньше любой текст уходил в поиск по каталогу, и
1 сентября бот ответил на «привет» списком из пятидесяти товаров, а на вопрос
«а почему на мой привет ты мне товарами отвечаешь?» — ещё пятьюдесятью. Поиск
перестал быть ответом по умолчанию: сначала выясняем, о чём вообще речь.

Разбор намеренно грубый. Он не заменяет модель, он отсекает очевидное.
"""

from __future__ import annotations

import re

GREETING = "greeting"
NORM_CODE = "norm_code"
NORM_QUESTION = "norm_question"
PRODUCT = "product"
SMALL_TALK = "small_talk"
# Описание задачи без предмета продажи: учреждение, помещение, возраст, «нужно
# оснастить», «с чего начать». Это ход консультанта, а не продавца.
TASK = "task"
OTHER = "other"

# «2.1.14», «п. 2.20.63», «пункт 1.13.3». Два уровня минимум: «2.4» тоже пункт,
# а вот «2024» или «25» — нет. Терминаторы — и знаки вопроса с тире: «1.13.2.3.9?»
# разбиралось как 1.13.2.3, а «2.30.1-2.30.6» — как 2.30 (прогон 04.10, К3).
_CODE = re.compile(r"(?:^|\s|п\.?\s*|пункт\s+)(\d{1,2}(?:\.\d{1,3}){1,5})(?=$|[\s,.;:!?)»\"']|[-–—])")
# Диапазон пунктов: «строго по 2.30.1–2.30.6».
_CODE_RANGE = re.compile(
    r"\b(\d{1,2}(?:\.\d{1,3}){1,5})\s*[-–—]\s*(\d{1,2}(?:\.\d{1,3}){1,5})\b"
)

_GREETING = re.compile(
    r"^\s*(?:привет\w*|здравствуй\w*|здрав\w+|добрый\s+(?:день|вечер|утр\w+)|"
    r"доброе\s+утро|доброго\s+\w+|здор\w+|салют|хай|ку|начать|start)\b[\s!.,)]*$",
    re.IGNORECASE,
)

# Разговор ни о чём и вежливость: на такое каталог отвечать не должен.
_SMALL_TALK = re.compile(
    r"^\s*(?:спасибо\w*|благодар\w+|пока\b|до\s+свидан\w+|всего\s+доброго|ага|угу|"
    r"ок\b|окей|хорошо|понятно|ясно|ладно|да\b|нет\b|как\s+дела|ты\s+кто|"
    r"вы\s+кто|ты\s+бот|вы\s+бот)\b[\s!.,?)]*$",
    re.IGNORECASE,
)

# Прямая просьба показать или подобрать. Именно она переключает консультанта на продавца.
# «Нужно оснастить», «нужна мебель» сюда больше не входят: это постановка задачи, и её
# разбирает консультант (NEXT-4.1).
_ASK_FOR_GOODS = re.compile(
    r"подбер\w+|подобра\w+|\bподбор\w*|покаж\w+|показать|что\s+есть|какие\s+есть|"
    r"хочу\s+купить|нужно\s+купить|есть\s+ли\s+у\s+вас|ищу\b|найди\w*|варианты|"
    r"сколько\s+стоит",
    re.IGNORECASE,
)

# Названный предмет продажи — конкретный товар, а не помещение и не категория. «Группа»,
# «кабинет», «зал», «логопед» описывают задачу: 13.09 по слову «группа» ход уходил
# продавцу, и консультант не получал слова вовсе. Слова ограничены по границам: иначе
# «стол» находился в «столовой», а «мат» — в «математике».
_GOODS = re.compile(
    r"\b(?:мяч\w*|обруч\w*|скакалк\w*|мат(?:ы|ов|ам|а)?|коврик\w*|ков[её]р\w*|ковр\w+|"
    r"стол(?:ы|ов|а|у|ик\w*)?|стул\w*|парт(?:а|ы|у|ой)|шкаф\w*|кроват\w*|стеллаж\w*|"
    r"скамейк\w*|скам(?:ья|ьи|ью|ей)|станок|станк\w+|доск\w+|проектор\w*|панел\w+|"
    r"ноутбук\w*|компьютер\w*|принтер\w*|игрушк\w+|конструктор\w*|кубик\w*|пирамидк\w*|"
    r"модул\w+|тренаж[её]р\w*|батут\w*|канат\w*|кегл\w*|мольберт\w*|микроскоп\w*|"
    r"пробирк\w*|посуд\w+|кресл\w+|стенк\w+|лестниц\w+|горк\w+|качел\w+|песочниц\w+|"
    r"зеркал\w*|диван\w*|пуф\w*|тележк\w+|самокат\w*|велосипед\w*|пособи\w+)\b",
    re.IGNORECASE,
)

# Постановка задачи: человек говорит, что ему нужно, а не называет товар.
_NEED = re.compile(
    r"\bнужн\w*|\bнадо\b|\bтребу\w*|оснасти\w*|оснащ\w*|укомплект\w*|закуп\w*|"
    r"\bкупит\w*|приобре\w*|открыва\w*|\bоткрыл\w*|ремонт\w*|оборудован\w*|мебел\w*|"
    r"инвентар\w*|комплект\w*|\bхоти\w*|\bхочу\b|планиру\w*|с\s+чего\s+начать",
    re.IGNORECASE,
)

# Служебные слова не делают реплику длиннее: «столы и стулья для группы» — это
# перечень товаров, а не рассказ.
_STOP_WORDS = frozenset(
    "и в во на для с со к по у а о об от до из за же ли мне нам нас".split()
)
SHORT_REPLY_WORDS = 4

# Вопрос о самом документе. Точный разбор — в `norms.reference`; здесь только
# грубый признак, чтобы не тащить в этот модуль нормативный слой.
_NORM_QUESTION = re.compile(
    r"(?:что\s+(?:такое|значит|за)|расскаж\w+|объясн\w+|зачем|почему|"
    r"на\s+основании|обязан\w+|по\s+как\w+|как\w+\s+приказ\w*|каким\s+)"
    r"\D{0,40}(?:приказ|перечен\w+|фгос|фоп|норматив)",
    re.IGNORECASE,
)
# «По какому приказу оснащается детский сад» — вопрос о документе, хотя ни
# «что такое», ни «объясни» в нём нет. 01.09 такой вопрос ушёл в товарную ветку,
# и человек получил полсотни случайных позиций вместо ответа.
_WHICH_DOCUMENT = re.compile(
    r"по\s+как\w+\s+(?:приказ\w*|перечн\w+|документ\w*)|"
    r"как\w+\s+(?:приказ\w*|перечн\w+|документ\w*)\D{0,20}(?:оснащ\w+|комплект\w+|закупа\w+)|"
    r"на\s+основании\s+чего",
    re.IGNORECASE,
)


def norm_code(text: str) -> str | None:
    """Номер пункта перечня, если он назван."""
    match = _CODE.search(f" {text or ''} ")
    return match.group(1) if match else None


def norm_codes(text: str) -> list[str]:
    """Все названные пункты. Диапазон «2.30.1-2.30.6» раскрывается в список (BUG-09)."""
    plain = f" {text or ''} "
    result: list[str] = []
    rest = plain
    for match in _CODE_RANGE.finditer(plain):
        expanded = _expand_code_range(match.group(1), match.group(2))
        if expanded:
            result += [code for code in expanded if code not in result]
            rest = rest.replace(match.group(0), " ")
    for match in _CODE.finditer(rest):
        if match.group(1) not in result:
            result.append(match.group(1))
    return result


def _expand_code_range(first: str, last: str) -> list[str]:
    """«2.30.1–2.30.6» → шесть кодов с общим префиксом. Разные префиксы — не диапазон."""
    left, right = first.split("."), last.split(".")
    if len(left) != len(right) or left[:-1] != right[:-1]:
        return []
    low, high = int(left[-1]), int(right[-1])
    if not 0 <= high - low <= 60:
        return []
    prefix = ".".join(left[:-1])
    return [f"{prefix}.{n}" for n in range(low, high + 1)]


def asks_for_goods(text: str) -> bool:
    """Прямая просьба показать оборудование.

    Такая реплика в ветке консультирования переключает разговор на продавца:
    заказчик отдельно оговорил, что «подбери мне оборудование для кабинета
    логопеда в детском саду» — это уже подбор, а не консультация.
    """
    return bool(_ASK_FOR_GOODS.search(text or ""))


# Вопрос о смысле пункта, а не просьба показать по нему товары: «что такое
# пункт 2.1.14», «что входит в 1.13.3». Разница видна только по обороту.
_ABOUT_CODE = re.compile(
    r"(?:что\s+(?:такое|значит|за|входит)|расскаж\w+|объясн\w+|как\s+звучит|"
    r"формулировк\w+|существу\w+\s+ли|есть\s+ли\s+(?:у\s+вас\s+)?так\w+\s+пункт|"
    r"у\s+вас\s+есть|текст\s+пункта)",
    re.IGNORECASE,
)


# Просьба показать ещё или другое — в отличие от вопроса о том, что уже показано.
_SHOW = re.compile(
    r"подбер\w+|подобра\w+|\bподбор\w*|покаж\w+|показать|найди\w*|\bищу\b|что\s+есть|"
    r"какие\s+есть|варианты|\bещ[её]\b|\bдруг\w+|дешевле",
    re.IGNORECASE,
)


def asks_to_show(text: str) -> bool:
    """Просит ли человек показать позиции — новые, другие, ещё.

    «Чем эти мячи полезны?» и «сколько стоит первый?» — вопросы о показанном: на них
    отвечают презентацией, а не новым подбором. Прогон 14.09: подбор по такой реплике
    искал товар «расскажите коротко чем эти мячи полезны» и принёс шнур.
    """
    return bool(_SHOW.search(text or ""))


def names_goods(text: str) -> bool:
    """Назван ли конкретный товар — не помещение и не категория."""
    return bool(_GOODS.search(text or ""))


def describes_task(text: str) -> bool:
    """Описана ли задача: что нужно, для какого учреждения, помещения, возраста."""
    if _NEED.search(text or ""):
        return True
    from core.profile import DialogProfile  # профиль импортирует нормативный слой — только здесь

    facts = DialogProfile().update_from_text(text or "")
    return bool({"institution", "room", "age"} & set(facts))


def is_short(text: str) -> bool:
    """Короткая реплика — перечень, а не рассказ: «столы и стулья для группы»."""
    words = [word for word in re.findall(r"[а-яёa-z0-9-]+", (text or "").lower()) if word not in _STOP_WORDS]
    return len(words) <= SHORT_REPLY_WORDS


# «Подбери из наличия 30 позиций и дай списком», «выведи 20 товаров» — просьба о перечне, а не о
# трёх карточках (прогон 14.09).
_LIST_SIZE = re.compile(r"\b(\d{1,3})\s+(?:позици\w*|товар\w*|наименовани\w*|вариант\w*)", re.IGNORECASE)
_LIST_ASK = re.compile(
    r"списк\w*|список|перечн\w*|подбер\w*|подобра\w*|выведи\w*|покаж\w*|\bдай\w*|пришли\w*", re.IGNORECASE
)
MAX_LIST = 50
# «А ещё что есть», «покажи ещё», «ещё варианты» — следующая страница того же подбора, без новых слов.
_MORE_ONLY = re.compile(
    r"^\s*(?:а\s+|и\s+)?(?:что\s+)?(?:ещ[её]|дальше)"
    r"(?:\s+(?:что|есть|что-нибудь|варианты|позиции|товары|покажи\w*|давай\w*|у\s+вас))*\s*[?!.]*\s*$|"
    r"^\s*(?:покажи\w*|показать|давай\w*)\s+ещ[её](?:\s+\w+)?\s*[?!.]*\s*$",
    re.IGNORECASE,
)


def list_size(text: str) -> int | None:
    """Сколько позиций человек просит одним списком. `None` — обычный подбор страницей."""
    match = _LIST_SIZE.search(text or "")
    if match is None or not _LIST_ASK.search(text or ""):
        return None
    size = int(match.group(1))
    return min(size, MAX_LIST) if size > 3 else None


def asks_more(text: str) -> bool:
    """Просьба о следующей странице подбора — без новых слов запроса."""
    return bool(_MORE_ONLY.match(text or ""))


def classify(text: str) -> str:
    """Одно из: greeting, small_talk, norm_code, norm_question, product, task, other.

    Порядок проверок выстрадан журналом.

    «Что значит приказ 1057 и подбери товары по нему» уходило консультанту, у
    которого нет поисковых инструментов, — и подбор состоял из отсылок к прошлой
    выдаче. Поэтому нормативный вопрос считается вопросом, только если в реплике
    нет просьбы показать товар.

    Обратный случай — «что такое пункт 2.1.14» — считался товарным запросом
    просто потому, что номер проверялся первым, и человек вместо объяснения
    получал карточки.

    Товар — это названный предмет, а не помещение. 13.09 «открываем новую группу, с чего
    начать закупку» уходило продавцу из-за слова «группа», и продавец обещал подбор, не
    имея предмета продажи. Теперь описание задачи — учреждение, помещение, возраст,
    «нужно оснастить» — это `task`, ход консультанта. Предмет в длинном рассказе без
    просьбы и без задачи правилом не решается: его разбирает модель.
    """
    text = (text or "").strip()
    if not text:
        return OTHER
    if _GREETING.match(text):
        return GREETING
    if _SMALL_TALK.match(text):
        return SMALL_TALK
    if norm_code(text):
        # Вопрос о пункте («что за п. 1.12.5? покажите формулировку») побеждает
        # «покажите»: иначе вместо текста приказа приходили товары (BUG-14).
        return NORM_QUESTION if _ABOUT_CODE.search(text) else NORM_CODE
    wants_goods = bool(_ASK_FOR_GOODS.search(text))
    if (_NORM_QUESTION.search(text) or _WHICH_DOCUMENT.search(text)) and not wants_goods:
        return NORM_QUESTION
    if wants_goods:
        return PRODUCT
    task = describes_task(text)
    if names_goods(text) and (task or is_short(text)):
        return PRODUCT
    if task:
        return TASK
    return OTHER


# «Подбери по этому заказу», «что есть из файла» — список по присланному заказу, а не новый подбор.
_ORDER_REF = re.compile(
    r"\bпо\s+(?:этому|моему|присланному|загруженному|отправленному|нашему|своему)?\s*(?:заказу|файлу|документу)\b|"
    r"\bиз\s+(?:этого\s+|моего\s+|присланного\s+)?(?:заказа|файла)\b",
    re.IGNORECASE,
)


def mentions_order(text: str) -> bool:
    return bool(_ORDER_REF.search(text or ""))


# «Сформируй предзаказ», «оформи», «все найденные позиции по 1 шт.» после присланного файла (15.09).
_ORDER_CHECKOUT = re.compile(
    r"оформ\w*|предзаказ\w*|\bв\s+корзин\w*|\bпо\s*\d{1,4}\s*(?:шт\w*|штук\w*|единиц\w*)", re.IGNORECASE
)
# «по 1 шт.», «по 2 штуки» — или «все по 2», «каждой по 3». «По приказу 1057» количеством не считается.
_EACH_QUANTITY = re.compile(
    r"\bпо\s*(\d{1,4})\s*(?:шт\w*|штук\w*|единиц\w*)|(?:\bвсе\w*|\bкажд\w+)\D{0,40}?\bпо\s*(\d{1,4})\b(?![.,]\d)",
    re.IGNORECASE,
)


# «Оформить», «оформим», «выставьте счёт», «готовы заказать» — просьба оформить заказ словами.
# Вопрос «как оформить доставку?» просьбой не считается, и «оформление занимает неделю» тоже:
# ядру тут нечего делать, на такое отвечает консультант.
_CHECKOUT = re.compile(
    r"\bоформ(?:ить|им|ите|и|ляйте)\b|\bпредзаказ\w*|\bвыстав\w+\s+счет\w*|\bсчет\s+на\s+оплат\w*|"
    r"\bготов\w*\s+(?:заказ\w*|оформ\w*)",
    re.IGNORECASE,
)


# Разговор О заказе, а не заказ: «в файле 88 позиций - проверь, ты выдаешь предзаказ только
# на 8» содержит слово «предзаказ», но оформлять не просит. 21.09 такая реплика запускала
# визард анкеты вместо ответа консультанта — вопрос клиента так и остался без ответа.
_META_TALK = re.compile(
    r"почему|зачем|провер\w*|перепровер\w*|исправ\w*|ошибк\w*|глюч\w*|\bбаг\w*|непонятн\w*|"
    r"что\s+за\s|дубл\w*|ты\s+(?:выда\w*|присыл\w*|собрал|неправ)",
    re.IGNORECASE,
)


def asks_checkout(text: str) -> bool:
    """Просьба оформить заказ — без присланного файла (`asks_order_checkout` — по нему)."""
    plain = (text or "").lower().replace("ё", "е")
    return "?" not in plain and not _META_TALK.search(plain) and bool(_CHECKOUT.search(plain))


def asks_order_checkout(text: str) -> bool:
    """Просьба оформить или положить в корзину — по присланному заказу, если он есть."""
    plain = (text or "").lower().replace("ё", "е")
    return not _META_TALK.search(plain) and bool(
        _ORDER_CHECKOUT.search(plain) or _EACH_QUANTITY.search(plain)
    )


def asks_about_order(text: str) -> bool:
    """Вопрос или претензия о заказе: данными анкеты такая реплика не становится.

    «А можно доставку в другой регион?» посреди оформления — вопрос, а не название
    организации; анкета переспрашивает свой шаг, а не глотает реплику.
    """
    plain = (text or "").lower().replace("ё", "е")
    return "?" in plain or bool(_META_TALK.search(plain))


# Сроки и график поставок. Ночью 16.09 это самый частый вопрос без ответа: «сколько по
# времени от оформления до счёта», «график поставок по этапам», «когда менеджер свяжется».
# Таких данных у бота нет ни в каталоге, ни в приказах — отвечает менеджер по заявке.
_DEADLINE = re.compile(
    r"(?:скольк\w*|как\w*|котор\w*)[^.?\n]{0,40}(?:времен\w*|дн\w+|недел\w*|срок\w*)|"
    r"\bсрок\w*\s+(?:от|до|постав\w*|изготовлени\w*|оформлени\w*|выставлени\w*)|"
    r"\b(?:график|этап\w*)\w*\s+(?:постав\w*|отгрузк\w*|оплат\w*)|"
    r"\bпостав\w*\s+(?:по\s+)?этапам|"
    r"\bкогда\b[^.?\n]{0,40}(?:счет|счёт|менеджер\w*|свяж\w*|привез\w*|отгруз\w*|получ\w*)",
    re.IGNORECASE,
)


# Срок службы, годности и гарантии — свойство товара: о нём отвечают карточка и описание.
_PRODUCT_LIFETIME = re.compile(
    r"срок\w*\s+(?:службы|годности|эксплуатаци\w*|хранени\w*|гаранти\w*)|гарантийн\w+\s+срок",
    re.IGNORECASE,
)


def asks_deadline(text: str) -> bool:
    """Спрашивают ли о сроке, счёте или графике поставок — о том, что знает только менеджер."""
    plain = (text or "").replace("ё", "е")
    return bool(_DEADLINE.search(plain)) and not _PRODUCT_LIFETIME.search(plain)


# Пункт перечня в реплике и количество рядом с ним: «1.5.1.6 Гимнастическая стенка — 4 шт.».
# Дата 25.12.2024 пунктом не считается: в пункте не больше трёх цифр в группе.
_POINT = re.compile(r"(?<![\d.,])(\d{1,2}(?:\.\d{1,3}){2,5})(?![\d.])")
_PIECES = re.compile(r"(\d{1,4})\s*(?:шт|штук|компл|набор|ед\b|единиц)\w*", re.IGNORECASE)


def listed_points(text: str) -> list[tuple[str, int | None]]:
    """Пункты перечня из реплики с количеством: «1.5.1.6 Гимнастическая стенка — 4 шт.» → («1.5.1.6», 4).

    Человек перечисляет комплектацию своими словами — списком, который до этого прислал бот, —
    и добавляет «сформируй предзаказ». 16.09 такая реплика упиралась в «корзина пуста»: ядро
    искало показанные карточки, а их в разговоре про пункты приказа не было.
    """
    plain = text or ""
    points: list[tuple[str, int | None]] = []
    seen: set[str] = set()
    found = list(_POINT.finditer(plain))
    for number, match in enumerate(found):
        code = match.group(1)
        if code in seen:
            continue
        seen.add(code)
        end = found[number + 1].start() if number + 1 < len(found) else len(plain)
        # Количество ищем до следующего пункта и не дальше строки: «4 шт.» из соседнего пункта чужое.
        pieces = _PIECES.search(plain[match.end() : end].split("\n")[0])
        points.append((code, int(pieces.group(1)) or None if pieces else None))
    return points


def each_quantity(text: str) -> int | None:
    """Количество каждой позиции, названное в реплике: «все по 2» → 2."""
    match = _EACH_QUANTITY.search(text or "")
    if match is None:
        return None
    number = int(match.group(1) or match.group(2))
    return number or None


